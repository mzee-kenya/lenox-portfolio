export function iconForLabel(label: string): (p: IconProps) => ReactElement {
  const key = (label ?? "").toLowerCase();
  if (key.includes("github")) return GitHubIcon;
  if (key.includes("linkedin")) return LinkedInIcon;
  if (key.includes("whatsapp")) return WhatsAppIcon;
  if (key.includes("facebook")) return FacebookIcon;
  if (key.includes("instagram")) return InstagramIcon;
  if (key.includes("tiktok")) return TikTokIcon;
  if (key.includes("youtube")) return YouTubeIcon;
  if (key.includes("mail") || key.includes("email")) return MailIcon;
  if (key.includes("phone") || key.includes("whats")) return PhoneIcon;
  return ExternalIcon;
}